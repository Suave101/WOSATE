// Print a translated Program as a Lustre main node (JKind / Kind 2 dialect), so
// the exact proof obligations can be re-checked with the desktop tools.

const LUSTRE_TYPES = { bool: "bool", int: "int", real: "real" };
const PREC = { arrow: 1, "=>": 2, "<=>": 3, or: 4, and: 5, "=": 6, "<>": 6, "<": 6, "<=": 6, ">": 6, ">=": 6, "+": 7, "-": 7, "*": 8, "/": 8, div: 8, mod: 8 };

export function lustreName(name) {
  return name.replace(/[^A-Za-z0-9_]/g, "_");
}

function realLiteral(v) {
  return /[.eE]/.test(v) ? v : `${v}.0`;
}

export function printExpr(e, parentPrec = 0) {
  switch (e.op) {
    case "var":
      return lustreName(e.name);
    case "lit":
      if (e.type === "bool") return e.v ? "true" : "false";
      return e.type === "real" ? realLiteral(String(e.v)) : String(e.v);
    case "not":
      return `(not ${printExpr(e.args[0], 9)})`;
    case "neg":
      return `(-${printExpr(e.args[0], 9)})`;
    case "pre":
      return `pre(${printExpr(e.args[0])})`;
    case "toReal":
      return `real(${printExpr(e.args[0])})`;
    case "floor":
      return `floor(${printExpr(e.args[0])})`;
    case "ite":
      return `(if ${printExpr(e.args[0])} then ${printExpr(e.args[1])} else ${printExpr(e.args[2])})`;
    case "arrow": {
      const s = `${printExpr(e.args[0], PREC.arrow + 1)} -> ${printExpr(e.args[1], PREC.arrow)}`;
      return parentPrec > PREC.arrow ? `(${s})` : s;
    }
    default: {
      const p = PREC[e.op];
      const op = e.op === "<=>" ? "=" : e.op;
      const s = `${printExpr(e.args[0], p)} ${op} ${printExpr(e.args[1], p + 1)}`;
      return parentPrec > p ? `(${s})` : s;
    }
  }
}

export function toLustre(program) {
  const lines = [];
  const ins = program.inputs;
  const locals = program.locals;
  lines.push(`-- Generated by WOSATE AGREE from ${program.name}`);
  lines.push(`-- Check with: jkind main.lus   (or: kind2 main.lus)`);
  lines.push("");
  lines.push("node main(");
  lines.push(ins.map((v) => `  ${lustreName(v.name)} : ${LUSTRE_TYPES[v.type]}`).join(";\n"));
  lines.push(") returns ();");
  const propVars = program.props.map((p, i) => ({ name: `__prop_${i}`, p }));
  const assertVars = program.asserts.map((a, i) => ({ name: `__assert_${i}`, a }));
  if (locals.length || propVars.length || assertVars.length) {
    lines.push("var");
    for (const v of locals) lines.push(`  ${lustreName(v.name)} : ${LUSTRE_TYPES[v.type]};`);
    for (const { name } of [...assertVars, ...propVars]) lines.push(`  ${name} : bool;`);
  }
  lines.push("let");
  for (const v of locals) lines.push(`  ${lustreName(v.name)} = ${printExpr(v.expr)};`);
  for (const { name, a } of assertVars) {
    lines.push(`  -- ${a.label}`);
    lines.push(`  ${name} = ${printExpr(a.expr)};`);
    lines.push(`  assert ${name};`);
  }
  for (const { name, p } of propVars) {
    lines.push(`  -- ${p.name}`);
    lines.push(`  ${name} = ${printExpr(p.expr)};`);
    lines.push(`  --%PROPERTY ${name};`);
  }
  lines.push("tel;");
  return lines.join("\n") + "\n";
}

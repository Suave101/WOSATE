function designDocument(model, root, arinc) {
  const esc = xml;
  const ts = threads(model, root);
  const rows = (cols, data) => `<table><tr>${cols.map((c) => `<th>${esc(c)}</th>`).join("")}</tr>${data.map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join("")}</tr>`).join("")}</table>`;
  const comps = [...root.walk()];
  const parts = [];
  parts.push(`<h1>${esc(root.classifier.pkg)}::${esc(root.classifier.name)}</h1><p class="muted">System design description generated by WOSATE on ${new Date().toISOString().slice(0, 10)} — ${comps.length} components, ${comps.reduce((s, c) => s + c.connections.length, 0)} connections, ${ts.length} threads.</p>`);
  parts.push(`<h2>1. Component hierarchy</h2>${rows(["Component", "Category", "Classifier", "Features"], comps.map((c) => [`${"&nbsp;&nbsp;".repeat(c.path ? c.path.split(".").length : 0)}${esc(c.parent ? c.name : c.name)}`, esc(c.category), esc(c.classifier ? `${c.classifier.pkg}::${c.classifier.name}` : "—"), String(c.features.length)]))}`);
  parts.push(`<h2>2. Architecture diagrams</h2>${comps.filter((c) => c.children.length).map((c) => `<h3>${esc(c.qualifiedPath)} (${esc(c.implementation?.name || "")})</h3><div class="svg">${diagramSvg(c)}</div>`).join("")}`);
  const ifaceTypes = [...new Set(comps.map((c) => model.typeOf(c.classifier)).filter(Boolean))];
  parts.push(`<h2>3. Interfaces</h2>${ifaceTypes.filter((t) => model.allFeatures(t).length).map((t) => `<h3>${esc(t.category)} ${esc(t.pkg)}::${esc(t.name)}</h3>${rows(["Feature", "Direction / access", "Kind", "Type"], model.allFeatures(t).map((f) => [`<code>${esc(f.name)}</code>`, esc(f.direction || f.access || ""), esc(f.featureKind || ""), esc(f.classifier?.name || "")]))}`).join("")}`);
  parts.push(`<h2>4. Connections</h2>${rows(["Owner", "Connection", "Kind", "Source", "Destination"], comps.flatMap((o) => o.connections.map((c) => [esc(o.qualifiedPath), `<code>${esc(c.name)}</code>`, esc(c.kind), esc(c.src.name), esc(c.dst.name)])))}`);
  parts.push(`<h2>5. Threads and timing</h2>${rows(["Thread", "Dispatch", "Period", "WCET", "Priority", "Bound to"], ts.map((t) => [esc(t.inst.qualifiedPath), esc(t.protocol), formatBase(t.period, "time"), t.wcet ? `${formatBase(t.wcet[0], "time")} .. ${formatBase(t.wcet[1], "time")}` : "—", String(t.priority), esc(t.processor?.qualifiedPath || "—")]))}`);
  const bindings = comps.map((c) => [c, referenceTargets(model, c, "Actual_Processor_Binding")]).filter(([c, t]) => t.length && !(c.parent && referenceTargets(model, c.parent, "Actual_Processor_Binding").length));
  parts.push(`<h2>6. Deployment</h2>${bindings.length ? rows(["Component", "Processor binding"], bindings.map(([c, t]) => [esc(c.qualifiedPath), esc(t.map((x) => x.qualifiedPath).join(", "))])) : "<p class=\"muted\">No processor bindings.</p>"}`);
  if (arinc) {
    for (const m of arinc.modules) {
      parts.push(`<h2>7. ARINC 653 module ${esc(m.cpu.qualifiedPath)}</h2><p>Major frame ${formatBase(m.major, "time")}.</p>${rows(["Partition", "Id", "Criticality", "Processes", "Windows"], m.parts.map((p) => [esc(p.name), String(p.id), esc(p.crit), esc(p.processes.map((x) => x.qualifiedPath).join(", ")), m.windows.filter((w) => w.p === p).map((w) => `${formatBase(w.start, "time")} +${formatBase(w.dur, "time")}`).join(", ")]))}`);
    }
  }
  const props = comps.flatMap((c) => model.classifierProperties(c.classifier).filter((p) => !p.appliesTo.length).map((p) => [esc(c.qualifiedPath), `<code>${esc(p.name)}</code>`, esc(formatValue(p.value))]));
  parts.push(`<h2>${arinc ? 8 : 7}. Properties</h2>${rows(["Component", "Property", "Value"], props)}`);
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${esc(root.classifier.name)} — design description</title><style>${DOC_CSS}</style></head><body>${parts.join("\n")}</body></html>\n`;
}

// ---- analyses ------------------------------------------------------------------------------------

function run(kind) {
  return ({ model, instance }) => {
    const files = [];
    const sections = [];
    if (kind === "c" || kind === "all") files.push(...generateC(model, instance));
    if (kind === "ada" || kind === "all") files.push(...generateAda(model, instance));
    const arinc = kind === "arinc" || kind === "all" || kind === "doc" ? arincXml(model, instance) : null;
    if (arinc && kind !== "doc") files.push({ name: "arinc653/module.xml", text: arinc.text, mime: "application/xml" });
    if (kind === "arinc" && !arinc) return { status: "warning", summary: "No processor with virtual processors (ARINC 653 partitions) in the instance model", sections: [] };
    if (kind === "doc" || kind === "all") files.push({ name: `${instance.classifier.name.replace(/\./g, "_")}_design.html`, text: designDocument(model, instance, arinc), mime: "text/html" });
    const ts = threads(model, instance);
    if (kind === "c" || kind === "ada" || kind === "all") {
      sections.push({ title: "Threads", table: { columns: ["Thread", "Entry point", "Dispatch", "Period", "Priority"], rows: ts.map((t) => ({ cells: [t.inst.qualifiedPath, t.entry, t.protocol, formatBase(t.period, "time"), String(t.priority)] })) } });
      sections.push({ title: "Semantic connections", table: { columns: ["Source", "Destination", "Through"], rows: semanticConnections(instance).map((c) => ({ cells: [`${c.src.qualifiedPath}.${c.srcFeature.name}`, `${c.dst.qualifiedPath}.${c.dstFeature?.name}`, c.path.map((p) => p.name).join(" → ")] })) } });
    }
    if (arinc) {
      for (const m of arinc.modules) {
        sections.push({ title: `ARINC 653 schedule: ${m.cpu.qualifiedPath} (major frame ${formatBase(m.major, "time")})`, table: { columns: ["Partition", "Id", "Window start", "Duration", "Processes"], rows: m.windows.map((w) => ({ cells: [w.p.name, String(w.p.id), formatBase(w.start, "time"), formatBase(w.dur, "time"), w.p.processes.map((p) => p.qualifiedPath).join(", ")] })) } });
      }
    }
    const preview = files.find((f) => f.name.endsWith("main.c")) || files.find((f) => f.name.endsWith(".xml")) || files.find((f) => f.name.endsWith(".ads"));
    if (preview) sections.push({ title: preview.name, code: preview.text });
    return { status: "ok", summary: `Generated ${files.length} file${files.length === 1 ? "" : "s"} for ${instance.name}`, sections, files };
  };
}


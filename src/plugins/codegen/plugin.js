// Code and configuration generators (in the spirit of Ocarina / TASTE, run in
// the browser): C (POSIX threads) and Ada (Ravenscar-style tasks) skeletons,
// an ARINC 653 module configuration XML, and an HTML system design document
// that prints to PDF.

import { instanceProperty, referenceTargets } from "../../core/instance.js";
import { toBase, formatBase, formatValue } from "../../core/properties.js";
import { diagramSvg } from "../instance-view.js";
import { ident, dataTypes, cType, cTypedef, adaType, adaTypedef, threads, semanticConnections, dataSize } from "./common.js";

const lc = (s) => (s || "").toLowerCase();
const ms = (sec) => (sec === null || sec === undefined ? null : Math.round(sec * 1e6) / 1e3);
const xml = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const banner = (root, lang) => `${lang === "ada" ? "--" : "/*"} Generated by WOSATE from ${root.classifier.pkg}::${root.classifier.name} on ${new Date().toISOString().slice(0, 10)}.${lang === "ada" ? "" : " */"}`;

// ---- C -----------------------------------------------------------------------------------------

function generateC(model, root) {
  const files = [];
  const types = dataTypes(model, root);
  const ts = threads(model, root);
  const conns = semanticConnections(root);
  const typeOfFeature = (f) => cType(model, f.decl?._classifier);
  files.push({
    name: "c/include/aadl_types.h",
    text: [banner(root, "c"), "#ifndef AADL_TYPES_H", "#define AADL_TYPES_H", "", "#include <stdbool.h>", "#include <stdint.h>", "", ...types.map((c) => `/* ${c.pkg}::${c.name} */\n${cTypedef(model, c)}\n`), "#endif", ""].join("\n"),
  });
  // One shared buffer per semantic connection (data ports keep the latest sample).
  // One buffer per sending port; fan-out connections share it.
  const bufferOf = (c) => ident(`${c.src.qualifiedPath}_${c.srcFeature.name}`.replace(/\./g, "_"));
  const buffers = new Map();
  for (const c of conns) (buffers.get(bufferOf(c)) || buffers.set(bufferOf(c), []).get(bufferOf(c))).push(c);
  files.push({
    name: "c/include/aadl_ports.h",
    text: [banner(root, "c"), "#ifndef AADL_PORTS_H", "#define AADL_PORTS_H", "", "#include \"aadl_types.h\"", "",
      ...[...buffers].map(([name, cs]) => `${cs.map((c) => `/* ${c.src.qualifiedPath}.${c.srcFeature.name} -> ${c.dst.qualifiedPath}.${c.dstFeature?.name} via ${c.path.map((p) => p.name).join(", ")} */`).join("\n")}\nextern ${typeOfFeature(cs[0].srcFeature)} ${name};`),
      "", "#endif", ""].join("\n"),
  });
  const outVars = new Set();
  files.push({
    name: "c/src/aadl_ports.c",
    text: [banner(root, "c"), "#include \"aadl_ports.h\"", "", ...conns.filter((c) => {
      const v = ident(`${c.src.qualifiedPath}_${c.srcFeature.name}`.replace(/\./g, "_"));
      if (outVars.has(v)) return false;
      outVars.add(v);
      return true;
    }).map((c) => `${typeOfFeature(c.srcFeature)} ${ident(`${c.src.qualifiedPath}_${c.srcFeature.name}`.replace(/\./g, "_"))};`), ""].join("\n"),
  });
  for (const t of ts) {
    const ins = conns.filter((c) => c.dst === t.inst);
    const outs = t.inst.features.filter((f) => /port/.test(f.kind || "") && /out/.test(f.direction || ""));
    files.push({
      name: `c/src/${t.id}.c`,
      text: [
        banner(root, "c"),
        `/* Thread ${t.inst.qualifiedPath}: ${t.inst.classifier?.name || ""}, ${t.protocol}${t.period ? `, period ${ms(t.period)} ms` : ""}${t.wcet ? `, WCET ${ms(t.wcet[1])} ms` : ""} */`,
        "#include \"aadl_ports.h\"",
        "",
        `void ${t.entry}(void)`,
        "{",
        ...ins.map((c) => `  ${typeOfFeature(c.dstFeature)} ${ident(c.dstFeature.name)} = ${ident(`${c.src.qualifiedPath}_${c.srcFeature.name}`.replace(/\./g, "_"))}; /* in ${c.dstFeature.name} */`),
        ...outs.map((f) => `  /* out ${f.name}: write ${ident(`${t.inst.qualifiedPath}_${f.name}`.replace(/\./g, "_"))} */`),
        "  /* TODO: application code */",
        ...ins.map((c) => `  (void)${ident(c.dstFeature.name)};`),
        "}",
        "",
      ].join("\n"),
    });
  }
  files.push({
    name: "c/src/main.c",
    text: [
      banner(root, "c"),
      "#define _GNU_SOURCE",
      "#include <pthread.h>",
      "#include <sched.h>",
      "#include <stdio.h>",
      "#include <time.h>",
      "",
      ...ts.map((t) => `extern void ${t.entry}(void);`),
      "",
      "typedef struct { const char *name; void (*step)(void); long period_ns; int priority; } task_t;",
      "",
      "static task_t tasks[] = {",
      ...ts.map((t) => `  { "${t.inst.qualifiedPath}", ${t.entry}, ${t.period ? Math.round(t.period * 1e9) : 0}L, ${t.priority} },${t.protocol === "sporadic" ? " /* sporadic: minimum inter-arrival time */" : ""}`),
      "};",
      "",
      "static void *run(void *arg)",
      "{",
      "  task_t *t = arg;",
      "  struct timespec next;",
      "  clock_gettime(CLOCK_MONOTONIC, &next);",
      "  for (;;) {",
      "    t->step();",
      "    if (t->period_ns <= 0) break;",
      "    next.tv_nsec += t->period_ns;",
      "    while (next.tv_nsec >= 1000000000L) { next.tv_nsec -= 1000000000L; next.tv_sec++; }",
      "    clock_nanosleep(CLOCK_MONOTONIC, TIMER_ABSTIME, &next, NULL);",
      "  }",
      "  return NULL;",
      "}",
      "",
      "int main(void)",
      "{",
      `  pthread_t threads[${Math.max(1, ts.length)}];`,
      "  for (unsigned i = 0; i < sizeof tasks / sizeof tasks[0]; i++) {",
      "    pthread_attr_t attr;",
      "    struct sched_param sp = { .sched_priority = tasks[i].priority };",
      "    pthread_attr_init(&attr);",
      "    pthread_attr_setschedpolicy(&attr, SCHED_FIFO);",
      "    pthread_attr_setschedparam(&attr, &sp);",
      "    if (pthread_create(&threads[i], &attr, run, &tasks[i]) != 0) {",
      "      /* Real-time scheduling needs privileges: fall back to default attributes. */",
      "      pthread_create(&threads[i], NULL, run, &tasks[i]);",
      "    }",
      "  }",
      "  for (unsigned i = 0; i < sizeof tasks / sizeof tasks[0]; i++) pthread_join(threads[i], NULL);",
      "  return 0;",
      "}",
      "",
    ].join("\n"),
  });
  files.push({
    name: "c/Makefile",
    text: ["# Generated by WOSATE", "CC ?= cc", "CFLAGS ?= -std=c11 -Wall -Wextra -O2 -Iinclude", "SRC := $(wildcard src/*.c)", "", `${ident(root.classifier.name)}: $(SRC)`, "\t$(CC) $(CFLAGS) -o $@ $^ -lpthread", "", "clean:", `\trm -f ${ident(root.classifier.name)}`, ""].join("\n"),
  });
  return files;
}

// ---- Ada -----------------------------------------------------------------------------------------

function generateAda(model, root) {
  const types = dataTypes(model, root);
  const ts = threads(model, root);
  const pkg = ident(root.classifier.name.split(".")[0]) + "_System";
  const spec = [
    banner(root, "ada"),
    "with Interfaces;",
    "with System;",
    "",
    `package ${pkg} is`,
    "   pragma Elaborate_Body;",
    "",
    ...types.map((c) => `   -- ${c.pkg}::${c.name}\n${adaTypedef(model, c)}`),
    "",
    ...ts.map((t) => `   task ${t.id} is\n      pragma Priority (System.Priority'First + ${t.priority});\n   end ${t.id};`),
    "",
    `end ${pkg};`,
    "",
  ].join("\n");
  const body = [
    banner(root, "ada"),
    "with Ada.Real_Time; use Ada.Real_Time;",
    "",
    `package body ${pkg} is`,
    "",
    ...ts.flatMap((t) => [
      `   -- ${t.inst.qualifiedPath}: ${t.protocol}${t.period ? `, period ${ms(t.period)} ms` : ""}`,
      `   task body ${t.id} is`,
      `      Period : constant Time_Span := Microseconds (${t.period ? Math.round(t.period * 1e6) : 100_000});`,
      "      Next   : Time := Clock;",
      "   begin",
      "      loop",
      `         null; -- ${t.entry}: application code`,
      "         Next := Next + Period;",
      "         delay until Next;",
      "      end loop;",
      `   end ${t.id};`,
      "",
    ]),
    `end ${pkg};`,
    "",
  ].join("\n");
  const unit = lc(pkg);
  return [
    { name: `ada/${unit}.ads`, text: spec },
    { name: `ada/${unit}.adb`, text: body },
    { name: "ada/main.adb", text: `${banner(root, "ada")}\nwith ${pkg};\nprocedure Main is\nbegin\n   null; -- tasks start at elaboration of ${pkg}\nend Main;\n` },
    { name: "ada/project.gpr", text: `project Project is\n   for Source_Dirs use (".");\n   for Main use ("main.adb");\n   package Compiler is\n      for Default_Switches ("Ada") use ("-gnat2012", "-gnatwa");\n   end Compiler;\nend Project;\n` },
  ];
}

// ---- ARINC 653 -------------------------------------------------------------------------------------

function arincConfig(model, root) {
  const processors = [...root.walk()].filter((i) => i.category === "processor");
  const semantic = semanticConnections(root);
  const modules = [];
  for (const cpu of processors) {
    const partitions = [...cpu.walk()].filter((i) => i.category === "virtual processor");
    if (!partitions.length) continue;
    const parts = partitions.map((vp, i) => {
      const id = instanceProperty(model, vp, "ARINC653::Partition_Identifier");
      const name = instanceProperty(model, vp, "ARINC653::Partition_Name");
      const crit = instanceProperty(model, vp, "ARINC653::Criticality");
      const processes = [...root.walk()].filter((p) => p.category === "process" && referenceTargets(model, p, "Actual_Processor_Binding").includes(vp));
      return { vp, id: id?.type === "number" ? id.value : i + 1, name: name?.type === "string" ? name.value : vp.name.toUpperCase(), crit: crit?.type === "name" ? crit.name : "LEVEL_E", processes };
    });
    const partitionOf = (proc) => parts.find((p) => p.processes.includes(proc));
    // Ports and channels: connections between processes in different partitions (or devices).
    const channels = [];
    const ports = new Map(parts.map((p) => [p, []]));
    for (const owner of root.walk()) {
      for (const c of owner.connections) {
        const s = c.src.component, d = c.dst.component;
        if (!s || !d || s === owner || d === owner) continue;
        const ps = s.category === "process" ? partitionOf(s) : null;
        const pd = d.category === "process" ? partitionOf(d) : null;
        if (!ps && !pd) continue;
        if (ps && pd && ps === pd) continue;
        const f = c.src.feature?.decl || c.dst.feature?.decl;
        const size = dataSize(model, f?._classifier) || 8;
        const queuing = /event/.test(f?.featureKind || "");
        // Refresh rate: the period of the thread (or device) that actually produces the data.
        const producer = semantic.find((sc) => sc.path.includes(c))?.src || s;
        const refresh = toBase(instanceProperty(model, producer, "Period"), "time") || 0.1;
        const portOf = (proc, feature, direction) => ({ name: `${proc.name}_${feature.name}`, direction, size, queuing, refresh });
        if (ps) ports.get(ps).push(portOf(s, c.src.feature, "SOURCE"));
        if (pd) ports.get(pd).push(portOf(d, c.dst.feature, "DESTINATION"));
        channels.push({ id: channels.length + 1, name: c.name, src: ps ? { partition: ps, port: `${s.name}_${c.src.feature.name}` } : { device: s.name, port: c.src.feature.name }, dst: pd ? { partition: pd, port: `${d.name}_${c.dst.feature.name}` } : { device: d.name, port: c.dst.feature.name } });
      }
    }
    // Schedule from ARINC653::Module_Schedule (records), else equal windows.
    const major = toBase(instanceProperty(model, cpu, "ARINC653::Module_Major_Frame"), "time");
    const sched = instanceProperty(model, cpu, "ARINC653::Module_Schedule");
    let windows = [];
    if (sched?.type === "list") {
      let start = 0;
      for (const rec of sched.items) {
        if (rec.type !== "record") continue;
        const target = rec.fields.partition?.type === "reference" ? rec.fields.partition.path.split(".").reduce((c, part) => c?.child(part), cpu) : null;
        const dur = toBase(rec.fields.duration, "time") || 0;
        const p = parts.find((x) => x.vp === target);
        if (p) windows.push({ p, start, dur, periodicStart: rec.fields.periodic_processing_start?.value === true });
        start += dur;
      }
    } else if (major) {
      windows = parts.map((p, i) => ({ p, start: (major / parts.length) * i, dur: major / parts.length, periodicStart: true }));
    }
    modules.push({ cpu, parts, ports, channels, major: major || windows.reduce((s, w) => s + w.dur, 0), windows });
  }
  return modules;
}

function arincXml(model, root) {
  const modules = arincConfig(model, root);
  if (!modules.length) return null;
  const sec = (x) => Number(x.toFixed(6));
  const out = ['<?xml version="1.0" encoding="UTF-8"?>', `<!-- Generated by WOSATE from ${xml(root.classifier.pkg)}::${xml(root.classifier.name)} -->`];
  for (const m of modules) {
    out.push(`<ARINC_653_Module ModuleName="${xml(m.cpu.qualifiedPath)}">`);
    for (const p of m.parts) {
      const ram = p.processes.flatMap((proc) => [...proc.walk()]).reduce((s, t) => s + (toBase(instanceProperty(model, t, "SEI::RAMBudget"), "size") || 0), 0);
      out.push(`  <Partition PartitionIdentifier="${p.id}" PartitionName="${xml(p.name)}" Criticality="${xml(p.crit)}" SystemPartition="false" EntryPoint="${xml(ident(p.name).toLowerCase())}_main">`);
      for (const port of m.ports.get(p)) {
        out.push(port.queuing
          ? `    <Queuing_Port Name="${xml(port.name)}" Direction="${port.direction}" MaxMessageSize="${Math.ceil(port.size)}" MaxNbMessages="8"/>`
          : `    <Sampling_Port Name="${xml(port.name)}" Direction="${port.direction}" MaxMessageSize="${Math.ceil(port.size)}" RefreshRateSeconds="${sec(port.refresh)}"/>`);
      }
      out.push("  </Partition>");
      out.push(`  <Partition_Memory PartitionIdentifier="${p.id}" PartitionName="${xml(p.name)}">`);
      out.push(`    <Memory_Requirements Type="DATA" SizeBytes="${Math.ceil(ram || 65536)}" Access="READ_WRITE"/>`);
      out.push("  </Partition_Memory>");
    }
    out.push(`  <Module_Schedule MajorFrameSeconds="${sec(m.major)}">`);
    for (const p of m.parts) {
      const ws = m.windows.filter((w) => w.p === p);
      out.push(`    <Partition_Schedule PartitionIdentifier="${p.id}" PartitionName="${xml(p.name)}" PeriodSeconds="${sec(m.major)}" PeriodDurationSeconds="${sec(ws.reduce((s, w) => s + w.dur, 0))}">`);
      ws.forEach((w, i) => out.push(`      <Window_Schedule WindowIdentifier="${p.id * 100 + i + 1}" WindowStartSeconds="${sec(w.start)}" WindowDurationSeconds="${sec(w.dur)}" PartitionPeriodStart="${w.periodicStart}"/>`));
      out.push("    </Partition_Schedule>");
    }
    out.push("  </Module_Schedule>");
    out.push("  <Connection_Table>");
    for (const ch of m.channels) {
      const end = (e) => (e.partition ? `<Standard_Partition PartitionIdentifier="${e.partition.id}" PartitionName="${xml(e.partition.name)}" PortName="${xml(e.port)}"/>` : `<Pseudo_Partition Name="${xml(e.device)}" PortName="${xml(e.port)}"/>`);
      out.push(`    <Channel ChannelIdentifier="${ch.id}" ChannelName="${xml(ch.name)}">`, `      <Source>${end(ch.src)}</Source>`, `      <Destination>${end(ch.dst)}</Destination>`, "    </Channel>");
    }
    out.push("  </Connection_Table>", "</ARINC_653_Module>");
  }
  return { text: out.join("\n") + "\n", modules };
}

